     * العمل الشائع في كل صفحة — يُستخدم لتسمية الصفحة من مسارها في السياق.
     * المصدر الفعلي للصفحات هو PlatformIndex (مشتق من الكود).
     */
    public static function pageLabel(string $path): string
    {
        foreach (PlatformIndex::pages() as $meta) {
            $route = $meta['path'];

            if ($path === $route) {
                return $meta['label_ar'];
            }

            if (str_contains($route, '{')) {
                $prefix = explode('{', $route)[0];

                if (str_starts_with($path, $prefix)) {
                    return $meta['label_ar'];
                }
            }
        }

        if (str_starts_with($path, '/courses/')) {
            return 'منشئ الكورس';
        }

        return trim($path, '/') ?: 'لوحة التحكم';
    }

